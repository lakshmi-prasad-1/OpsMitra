import { Link } from 'react-router-dom';
import { AlertTriangle, ArrowRight, BrainCircuit, CircleAlert, Info, Sparkles, TrendingUp } from 'lucide-react';
import { useApi, useDocumentTitle, useQueryState } from '../../lib/hooks.js';
import { compactMoney, money, moneyRound, titleCase } from '../../lib/format.js';
import { Badge, EmptyState, ErrorState, LinkButton, PageHeader, PageLoader, Panel, Tabs } from '../../components/ui.jsx';
import { SalesChart } from '../../components/Charts.jsx';

const ICON = { critical: CircleAlert, warning: AlertTriangle, info: Info, positive: TrendingUp };
const TONE = { critical: 'red', warning: 'amber', info: 'blue', positive: 'green' };
const CATEGORIES = [['all', 'All'], ['stock', 'Stock'], ['sales', 'Sales'], ['finance', 'Money'], ['customers', 'Customers'], ['products', 'Products']];

export default function Insights() {
  useDocumentTitle('Insights');
  const [f, setF] = useQueryState({ category: 'all' });
  const q = useApi(['insights'], '/insights', { staleTime: 30000 });
  if (q.isPending) return <PageLoader label="Analysing your records…" />;
  if (q.error) return <ErrorState error={q.error} onRetry={q.refetch} />;
  const d = q.data;
  const shown = d.insights.filter(i => f.category === 'all' || i.category === f.category);
  const chart = [...d.history.map(h => ({ date: h.date, sales: h.sales })), ...d.forecast.days.map(x => ({ date: x.date, predicted: x.predicted }))];
  // Join the dashed estimate to the last real point so the line looks continuous.
  if (d.history.length) { const last = chart[d.history.length - 1]; last.predicted = last.sales; }
  const counts = d.counts;

  return (
    <>
      <PageHeader title="Insights" subtitle="What needs your attention, and why — calculated from your own records." />
      <div className="callout" style={{ marginBottom: 20 }}>
        <BrainCircuit size={20} />
        <div><b>How these work.</b> OpsMitra applies transparent rules to your stock, sales, margins and credit. Every card shows the numbers behind it. Forecasts are statistical estimates from your weekday pattern, not guarantees, and nothing here is generated by an AI model — for free-form questions, try <Link to="/app/assistant" className="link">Ask OpsMitra</Link>.</div>
      </div>

      <div className="toolbar">
        <Tabs tabs={CATEGORIES.map(([k, l]) => [k, l, k === 'all' ? d.insights.length : d.insights.filter(i => i.category === k).length])} value={f.category} onChange={category => setF({ category })} />
        <div className="spacer" />
        {['critical', 'warning', 'info', 'positive'].filter(s => counts[s]).map(s => <Badge key={s} tone={TONE[s]} dot>{counts[s]} {s === 'positive' ? 'good news' : s}</Badge>)}
      </div>

      <div className="grid-main">
        <div>
          {shown.length === 0 ? <Panel><EmptyState icon={Sparkles} title="Nothing here yet" text="Insights appear as you add products and record sales, purchases and payments." action={<LinkButton to="/app/sales/new">Record a sale</LinkButton>} /></Panel> : shown.map(i => {
            const Icon = ICON[i.severity] || Info;
            return (
              <article key={i.id} className={`insight insight-${i.severity}`}>
                <i className={`insight-icon tone-${TONE[i.severity]}`}><Icon size={20} /></i>
                <div className="insight-main">
                  <div className="insight-title"><h3>{i.title}</h3><Badge tone={TONE[i.severity]}>{titleCase(i.severity === 'positive' ? 'good news' : i.severity)}</Badge></div>
                  <p>{i.description}</p>
                  <div className="rec"><strong>Recommended</strong><span>{i.recommendation}</span></div>
                  {i.evidence?.length > 0 && (
                    <div className="evidence">{i.evidence.map((e, n) => <div key={n}><small>{e.label}</small><b>{typeof e.value === 'number' ? (/revenue|sold|month|days|week/i.test(e.label) && e.value > 99 ? moneyRound(e.value) : e.value.toLocaleString('en-IN')) : e.value}</b></div>)}</div>
                  )}
                  {i.href && <Link to={i.href} className="link" style={{ display: 'inline-flex', gap: 6, alignItems: 'center', marginTop: 12 }}>Take a look <ArrowRight size={14} /></Link>}
                </div>
              </article>
            );
          })}
        </div>
        <div className="stack">
          <Panel title="Next 7 days (estimate)" subtitle="Based on your last 8 weeks">
            <div className="big-number">{money(d.forecast.total)}</div>
            <p className="muted" style={{ fontSize: 13.5, margin: '2px 0 8px' }}>expected sales, ±{Math.round(Math.abs(d.forecast.trendFactor - 1) * 100)}% recent trend applied</p>
            <div className="chart-box short"><SalesChart data={chart} /></div>
            <div className="legend" style={{ marginTop: 8 }}><span><i style={{ background: 'var(--chart-1)' }} />Actual</span><span><i style={{ background: 'var(--chart-2)' }} />Estimate</span></div>
            <div className="list" style={{ marginTop: 10 }}>{d.forecast.days.map(x => <div className="list-row" key={x.date} style={{ padding: '8px 0' }}><div><strong>{new Date(`${x.date}T12:00:00`).toLocaleDateString('en-IN', { weekday: 'long', day: 'numeric', month: 'short' })}</strong></div><span className="num">{compactMoney(x.predicted)}</span></div>)}</div>
          </Panel>
        </div>
      </div>
    </>
  );
}
